import importlib.util
import sys
import tempfile
import unittest
from pathlib import Path


ROOT = Path(__file__).resolve().parents[3]


def load(name: str, filename: str):
    path = ROOT / "tools" / "ci" / filename
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    sys.modules.setdefault(name, module)
    spec.loader.exec_module(module)
    return module


MODULE = load("regenerate_weights", "regenerate-weights.py")
PURITY = load("check_generated_weights", "check-generated-weights.py")
REGRESSION = MODULE.load_regression_module()
PARSE = REGRESSION.parse_weight_file


HEADER = """
//! Autogenerated weights for `pallet_example`
//!
//! THIS FILE WAS AUTO-GENERATED USING THE SUBSTRATE BENCHMARK CLI VERSION 58.0.0
//! DATE: 2026-07-26, STEPS: `{steps}`, REPEAT: `{repeat}`, LOW RANGE: `[]`, HIGH RANGE: `[]`

// Executed Command:
// frame-omni-bencher
// --output
// /tmp/somewhere/pallet_example.rs

use frame_support::{{traits::Get, weights::Weight}};
use core::marker::PhantomData;

/// Weight functions for `pallet_example`.
pub struct WeightInfo<T>(PhantomData<T>);
impl<T: frame_system::Config> pallet_example::WeightInfo for WeightInfo<T> {{
"""


def constant_fn(name: str, ref_time: int, proof: int, reads: int, writes: int) -> str:
    return (
        f"\t/// Storage: `Example::Thing` (r:{reads} w:{writes})\n"
        f"\tfn {name}() -> Weight {{\n"
        f"\t\t// Minimum execution time: {ref_time}_000 picoseconds.\n"
        f"\t\tWeight::from_parts({ref_time}_000, 0)\n"
        f"\t\t\t.saturating_add(Weight::from_parts(0, {proof}))\n"
        f"\t\t\t.saturating_add(T::DbWeight::get().reads({reads}))\n"
        f"\t\t\t.saturating_add(T::DbWeight::get().writes({writes}))\n"
        f"\t}}\n"
    )


def linear_fn(name: str, read_slope: int, high: int = 12) -> str:
    return (
        f"\t/// The range of component `n` is `[0, {high}]`.\n"
        f"\tfn {name}(n: u32, ) -> Weight {{\n"
        f"\t\t// Minimum execution time: 1_000_000 picoseconds.\n"
        f"\t\tWeight::from_parts(1_000_000, 0)\n"
        f"\t\t\t.saturating_add(Weight::from_parts(0, 500))\n"
        f"\t\t\t.saturating_add(T::DbWeight::get().reads(3))\n"
        f"\t\t\t.saturating_add(T::DbWeight::get()"
        f".reads(({read_slope}_u64).saturating_mul(n.into())))\n"
        f"\t\t\t.saturating_add(T::DbWeight::get().writes(1))\n"
        f"\t}}\n"
    )


def weight_file(body: str, steps: int = 50, repeat: int = 20) -> str:
    return HEADER.format(steps=steps, repeat=repeat) + body + "}\n"


