class RepositoryTests(unittest.TestCase):
    def test_every_committed_weight_file_declares_its_fidelity(self):
        for pallet, path in MODULE.committed_weight_files().items():
            text = path.read_text(encoding="utf-8")
            self.assertIsNotNone(
                MODULE.parse_fidelity(text),
                f"{pallet}: no `STEPS: ..., REPEAT: ...` header, so a --check run cannot "
                "know whether slope comparisons are exact",
            )
            self.assertIsNotNone(MODULE.parse_date(text), pallet)

    def test_every_committed_weight_file_parses(self):
        for pallet, path in MODULE.committed_weight_files().items():
            parsed = PARSE(path.read_text(encoding="utf-8"))
            self.assertGreater(len(parsed), 0, pallet)

    def test_preserved_functions_are_exactly_the_known_set(self):
        """Exactly one committed function is not backed by a fresh measurement.

        A preserved function needs no `generated-weight-overrides.toml` entry —
        it *is* generator output, measured-line and all, which is why the purity
        gate passes it. What it lacks is *freshness*, and nothing else records
        that. Pinning the set means a second one cannot appear unnoticed.
        """
        found = {
            pallet: MODULE.preserved_functions(path.read_text(encoding="utf-8"))
            for pallet, path in MODULE.committed_weight_files().items()
        }
        self.assertEqual(
            {pallet: names for pallet, names in found.items() if names},
            {
                # Fixture unsatisfiable in this runtime (weight-preservation.toml).
                "pallet_assets": ["migration_v2_foreign_asset_set_reserve_weight"],
                # `pallet_guardian::on_initialize` was here until SQ-500. It held a
                # hand-written envelope above a fixture that settled one review,
                # because the sweep had no per-block bound. The bound exists now
                # (13 §2 `GuardianMaintenanceBatch`), the fixture saturates it, and
                # the function is a fresh measurement — so it needs neither the
                # preserved marker nor its override entry.
            },
        )

    def test_the_release_fidelity_gate_exists_and_blocks_publication(self):
        """The release-time obligation must be implemented, not just written down.

        15 §4.5 makes matching-fidelity re-measurement of component-bearing
        functions a release-time duty. A normative sentence with no workflow behind
        it is exactly the artifact-versus-reality gap this row exists to close, so
        the job must exist *and* `publish` must depend on it — otherwise a release
        could ship on slopes verified at no fidelity at all.
        """
        workflow = (ROOT / ".github" / "workflows" / "release.yml").read_text(encoding="utf-8")
        self.assertIn("--check --components-only", " ".join(workflow.split()))
        self.assertIn("--steps 50 --repeat 20", " ".join(workflow.split()))
        parsed = None
        try:
            import yaml

            parsed = yaml.safe_load(workflow)
        except ImportError:  # pragma: no cover - pyyaml absent in some envs
            self.skipTest("pyyaml not installed")
        self.assertIn("release-fidelity-weights", parsed["jobs"])
        self.assertIn("release-fidelity-weights", parsed["jobs"]["publish"]["needs"])

    def test_the_drift_check_is_actually_wired_into_ci(self):
        """A gate nobody runs is not a gate.

        The previous step in this job executed every benchmark and threw the
        results away, which is why stale weights survived (SQ-490). If this
        assertion ever fails, the drift check has been unwired and the repo is
        back to detecting only benchmarks that crash.
        """
        workflow = (ROOT / ".github" / "workflows" / "ci.yml").read_text(encoding="utf-8")
        self.assertIn("tools/ci/regenerate-weights.py --check", workflow)


