class ComparisonTests(unittest.TestCase):
    def compare(self, committed: str, fresh: str, preserved=()) -> object:
        return MODULE.compare_pallet(
            "pallet_example", committed, fresh, list(preserved), PARSE
        )

    def test_identical_files_do_not_drift(self):
        result = self.compare(BASE, BASE)
        self.assertEqual(result.hard, [])
        self.assertEqual(result.advisory, [])
        self.assertEqual(result.measured, 1)
        self.assertFalse(result.failed)

    def test_changed_reads_is_a_hard_failure(self):
        """The original SQ-490 defect's shape: 8 declared reads, 261 performed."""
        fresh = weight_file(constant_fn("alpha", 5_000, 1_200, 261, 2))
        result = self.compare(BASE, fresh)
        self.assertTrue(result.failed)
        self.assertEqual([d.quantity for d in result.hard], ["worst_case.reads"])
        self.assertEqual((result.hard[0].committed, result.hard[0].fresh), (4, 261))

    def test_changed_proof_size_is_a_hard_failure(self):
        fresh = weight_file(constant_fn("alpha", 5_000, 99_999, 4, 2))
        self.assertEqual(
            [d.quantity for d in self.compare(BASE, fresh).hard], ["worst_case.proof_size"]
        )

    def test_constant_function_drift_is_hard_even_across_fidelities(self):
        """This is what makes a cheap per-commit run worth running.

        Constant-weight functions agree exactly across sampling fidelities
        (measured: `pallet_attestor` 6/6, `pallet_collator_selection` 2/2), so a
        2x1 CI run gates them soundly — and the original SQ-490 defect was exactly
        such a function.
        """
        committed = weight_file(constant_fn("alpha", 5_000, 1_200, 8, 2), steps=50, repeat=20)
        fresh = weight_file(constant_fn("alpha", 5_000, 1_200, 261, 2), steps=2, repeat=1)
        result = self.compare(committed, fresh)
        self.assertFalse(result.fidelity_matches)
        self.assertTrue(result.failed)
        self.assertEqual([d.quantity for d in result.hard], ["worst_case.reads"])

    def test_ref_time_alone_never_fails(self):
        """The measured jitter is up to 127 %; a ref_time delta is not a defect."""
        fresh = weight_file(constant_fn("alpha", 9_999, 1_200, 4, 2))
        result = self.compare(BASE, fresh)
        self.assertFalse(result.failed)
        self.assertEqual([d.quantity for d in result.advisory], ["base.ref_time"])

    def test_slope_change_is_hard_at_matching_fidelity(self):
        """At equal fidelity the fit is comparable, so a slope move is real."""
        committed = weight_file(linear_fn("beta", 5))
        fresh = weight_file(linear_fn("beta", 9))
        result = self.compare(committed, fresh)
        self.assertTrue(result.fidelity_matches)
        self.assertTrue(result.failed)
        # 3 + 5*12 = 63 against 3 + 9*12 = 111.
        self.assertEqual([d.quantity for d in result.hard], ["worst_case.reads"])
        self.assertEqual((result.hard[0].committed, result.hard[0].fresh), (63, 111))

    def test_component_function_is_advisory_across_fidelities(self):
        """Measured: a 2-point fit can lose a linear term outright.

        `pallet_collator_selection::new_session` reports worst-case writes 100 at
        50x20 and 3 at 2x1 — the low-fidelity fit drops the per-candidate slope
        completely. 5 of its 9 component functions disagree that way. A hard gate
        on component functions at mismatched fidelity would therefore fire on fit
        artifacts rather than defects, so they are advisory there and the release
        run at matching fidelity is what gates them.
        """
        committed = weight_file(linear_fn("beta", 5), steps=50, repeat=20)
        fresh = weight_file(linear_fn("beta", 9), steps=2, repeat=1)
        result = self.compare(committed, fresh)
        self.assertFalse(result.fidelity_matches)
        self.assertFalse(result.failed)
        self.assertIn("worst_case.reads", [d.quantity for d in result.advisory])

    def test_decomposition_shifts_that_preserve_the_total_are_silent(self):
        """`set_candidacy_bond` moves its slope 901 -> 1,306 with an unchanged total.

        Gating the intercept/slope split rather than the worst-case total would
        report that as drift, which is arithmetic noise, not a defect — the state
        that produced 42 spurious 'STALE' lines before this comparison was fixed.
        """
        # base 8 + 5*12 = 68; base 68 + 0*12 = 68. Same total, different split.
        committed = weight_file(linear_fn("beta", 5) .replace("reads(3)", "reads(8)"))
        fresh = weight_file(linear_fn("beta", 0).replace("reads(3)", "reads(68)"))
        result = self.compare(committed, fresh)
        self.assertFalse(result.failed, [d.describe() for d in result.hard])

    def test_base_reads_stay_hard_across_fidelities(self):
        committed = weight_file(constant_fn("alpha", 5_000, 1_200, 4, 2), 50, 20)
        fresh = weight_file(constant_fn("alpha", 5_000, 1_200, 7, 2), 2, 1)
        result = self.compare(committed, fresh)
        self.assertTrue(result.failed, "storage dimensions are fidelity-invariant")

    def test_component_range_growth_is_hard(self):
        committed = weight_file(linear_fn("beta", 5, high=12))
        fresh = weight_file(linear_fn("beta", 5, high=64))
        result = self.compare(committed, fresh)
        self.assertTrue(result.failed)
        self.assertIn("range.n.high", [d.quantity for d in result.hard])

    def test_a_function_no_benchmark_emits_is_a_hard_failure(self):
        """The SQ-490 defect: two functions hand-appended to a generated file."""
        committed = weight_file(
            constant_fn("alpha", 5_000, 1_200, 4, 2) + constant_fn("appended", 1_800, 48_000, 245, 245)
        )
        result = self.compare(committed, BASE)
        self.assertTrue(result.failed)
        self.assertEqual(result.removed, ["appended"])

    def test_a_new_benchmark_is_noted_not_failed(self):
        fresh = weight_file(
            constant_fn("alpha", 5_000, 1_200, 4, 2) + constant_fn("gamma", 100, 200, 1, 1)
        )
        result = self.compare(BASE, fresh)
        self.assertFalse(result.failed)
        self.assertEqual(result.added, ["gamma"])

    def test_a_preserved_function_is_never_counted_as_measured(self):
        committed = weight_file(
            constant_fn("alpha", 5_000, 1_200, 4, 2) + constant_fn("stuck", 7, 8, 9, 10)
        )
        result = self.compare(committed, committed, preserved=["stuck"])
        self.assertEqual(result.unmeasured, ["stuck"])
        self.assertEqual(result.measured, 1)
        self.assertFalse(result.failed)


class SpliceTests(unittest.TestCase):
    def test_function_block_carries_its_doc_comments(self):
        block = MODULE.extract_function_block(BASE, "alpha")
        self.assertIsNotNone(block)
        self.assertIn("/// Storage: `Example::Thing`", block)
        self.assertIn("fn alpha()", block)

    def test_missing_function_yields_none(self):
        self.assertIsNone(MODULE.extract_function_block(BASE, "absent"))

    def test_preserved_function_survives_regeneration(self):
        committed = weight_file(
            constant_fn("alpha", 5_000, 1_200, 4, 2) + constant_fn("stuck", 7_000, 8, 9, 10)
        )
        fresh = weight_file(constant_fn("alpha", 6_000, 1_200, 4, 2))
        merged = MODULE.splice_preserved(fresh, committed, ["stuck"], "unsatisfiable fixture")
        parsed = PARSE(merged)
        self.assertEqual(sorted(parsed), ["alpha", "stuck"])
        self.assertEqual(parsed["stuck"].reads, 9)
        self.assertIn("Preserved, not re-measured", merged)

    def test_spliced_output_still_passes_the_purity_gate(self):
        """The two tools must agree: a preserved function is generated output.

        `check-generated-weights.py` fails any function carrying a term outside
        the generator's grammar. If splicing produced something it rejected, this
        tool would be manufacturing the very defect SQ-490 removed.
        """
        committed = weight_file(
            constant_fn("alpha", 5_000, 1_200, 4, 2) + constant_fn("stuck", 7_000, 8, 9, 10)
        )
        fresh = weight_file(constant_fn("alpha", 6_000, 1_200, 4, 2))
        merged = MODULE.splice_preserved(fresh, committed, ["stuck"], "unsatisfiable fixture")
        for match in PURITY.FN_RE.finditer(merged):
            body = match.group(2)
            self.assertIn(PURITY.MEASURED_MARKER, body, match.group(1))
            self.assertEqual(PURITY.spliced_residue(body), "", match.group(1))

    def test_unknown_preserved_function_is_rejected(self):
        with self.assertRaises(MODULE.ToolError):
            MODULE.splice_preserved(BASE, BASE, ["absent"], "reason")


class PreservationControlTests(unittest.TestCase):
    """Preservation is a declared exemption, not a self-authorizing comment.

    The marker is what the tool writes, so if the marker were its own
    authorization anyone could convert "this weight is stale" into "this weight is
    exempt from the freshness gate" by adding a doc comment — and the gate would go
    quiet on a function whose real cost had grown without bound.
    """

    def load(self, body: str) -> dict:
        with tempfile.TemporaryDirectory() as raw:
            path = Path(raw) / "weight-preservation.toml"
            path.write_text(body, encoding="utf-8")
            return MODULE.load_preservations(path)

    def test_entry_is_parsed(self):
        parsed = self.load("w/pallet_a.rs stuck: upstream fixture asserts an empty map\n")
        self.assertEqual(parsed, {("w/pallet_a.rs", "stuck"): "upstream fixture asserts an empty map"})

    def test_comments_and_blanks_are_skipped(self):
        self.assertEqual(self.load("# note\n\n"), {})

    def test_missing_justification_is_rejected(self):
        with self.assertRaises(MODULE.ToolError):
            self.load("w/pallet_a.rs stuck:\n")

    def test_duplicate_entry_is_rejected(self):
        with self.assertRaises(MODULE.ToolError):
            self.load("w/a.rs f: one\nw/a.rs f: two\n")

    def test_repository_markers_and_declarations_agree(self):
        """Every marker is declared, in one file or the other.

        Two declarations confer the exemption: `weight-preservation.toml` (the
        fixture cannot run) and `generated-weight-overrides.toml` (the weight is
        deliberately hand-written). `--write` marks both, so a marker is legitimate
        if either file names it — and every marker must be named by one of them.
        """
        declared = set(MODULE.load_preservations()) | set(MODULE.load_purity_overrides())
        marked = {
            (path.relative_to(ROOT).as_posix(), function)
            for path in MODULE.committed_weight_files().values()
            for function in MODULE.preserved_functions(path.read_text(encoding="utf-8"))
        }
        self.assertEqual(marked - declared, set(), "marker with no declaration")
        # Preservation entries must be marked; a purity override need not be, since
        # a hand-written weight only acquires the marker once regenerated.
        self.assertEqual(
            set(MODULE.load_preservations()) - marked, set(), "declared but unmarked"
        )

    def test_every_declaration_explains_why_unverified_is_acceptable(self):
        for key, justification in MODULE.load_preservations().items():
            self.assertGreater(len(justification), 80, key)


class HandWrittenSurvivalTests(unittest.TestCase):
    """A regeneration must not replace a deliberate hand-written weight.

    Three exist: `pallet_xcm`'s two protocol-disabled calls hold a fail-closed
    `Weight::MAX` (09 §6.2), and `pallet_guardian::on_initialize` holds a
    conservative envelope that must stay above the one-settle measurement until
    SQ-500 bounds the sweep. Regenerating any of them would silently replace a
    deliberate value with a measured one — for the guardian hook, making a known
    undercharge worse.
    """

    def test_generated_definition_is_replaced_by_the_committed_one(self):
        committed = weight_file("\tfn execute() -> Weight {\n\t\tWeight::MAX\n\t}\n")
        fresh = weight_file(constant_fn("execute", 5_000, 1_200, 4, 2))
        merged = MODULE.substitute_preserved(fresh, committed, ["execute"], "fail-closed sentinel")
        self.assertIn("Weight::MAX", merged)
        self.assertNotIn("reads(4)", merged)
        self.assertEqual(merged.count("fn execute()"), 1, "duplicate definition would not compile")

    def test_absent_definition_is_inserted(self):
        committed = weight_file(
            constant_fn("alpha", 1, 1, 1, 1) + constant_fn("only_committed", 7_000, 8, 9, 10)
        )
        fresh = weight_file(constant_fn("alpha", 1, 1, 1, 1))
        merged = MODULE.substitute_preserved(fresh, committed, ["only_committed"], "reason")
        self.assertEqual(sorted(PARSE(merged)), ["alpha", "only_committed"])

    def test_every_purity_override_is_a_real_committed_function(self):
        files = MODULE.committed_weight_files()
        for (rel, function) in MODULE.load_purity_overrides():
            path = ROOT / rel
            self.assertTrue(path.is_file(), rel)
            self.assertIn(Path(rel).stem, files)
            block = MODULE.extract_function_block(path.read_text(encoding="utf-8"), function)
            self.assertIsNotNone(block, f"{rel}::{function} not extractable for preservation")


class ComponentSelectionTests(unittest.TestCase):
    def test_component_bearing_pallets_are_a_strict_subset(self):
        """The release gate's scope is derived from the files, not hand-listed."""
        files = MODULE.committed_weight_files()
        with_components = [
            pallet
            for pallet, path in files.items()
            if any(w.ranges for w in PARSE(path.read_text(encoding="utf-8")).values())
        ]
        self.assertTrue(with_components)
        self.assertLess(len(with_components), len(files))
        # `pallet_epoch` carries `tick`/`settle_cohort` component slopes and is the
        # one custom pallet verified at matching fidelity on this branch.
        self.assertIn("pallet_epoch", with_components)
        # `pallet_attestor` is constant-weight throughout — the class the cheap
        # per-commit run gates soundly, and the class the original defect was in.
        self.assertNotIn("pallet_attestor", with_components)


class LastImplScopingTests(unittest.TestCase):
    """A shadowed definition in an earlier impl must never be the one copied.

    `check-weight-regression.py` keeps the LAST `WeightInfo` impl per file, so any
    reader of a function's committed source has to scope to the same block.
    """

    def test_preserved_body_comes_from_the_last_impl(self):
        shadowed = weight_file(constant_fn("stuck", 1, 1, 1, 1))
        real = "impl<T: frame_system::Config> pallet_example::WeightInfo for Other<T> {\n"
        source = shadowed.rstrip()[: -len("}")] + "}\n" + real + constant_fn(
            "stuck", 7_000, 8, 9, 10
        ) + "}\n"
        block = MODULE.extract_function_block(source, "stuck")
        self.assertIn("reads(9)", block)
        self.assertNotIn("reads(1)", block)

    def test_marker_in_an_earlier_impl_is_not_counted(self):
        source = (
            "impl<T> pallet_example::WeightInfo for Old<T> {\n"
            "\t/// **Preserved, not re-measured** — historical\n"
            + constant_fn("gone", 1, 1, 1, 1)
            + "}\n"
            "impl<T> pallet_example::WeightInfo for WeightInfo<T> {\n"
            + constant_fn("alpha", 1, 1, 1, 1)
            + "}\n"
        )
        self.assertEqual(MODULE.preserved_functions(source), [])


